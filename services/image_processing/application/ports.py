from typing import Protocol
from services.image_processing.domain.models import CutoutRequest, ImageReference


class ScientificObjectStore(Protocol):
    def read(self, reference: ImageReference) -> bytes: ...
    def write(self, data: bytes, content_type: str) -> ImageReference: ...


class FitsProcessor(Protocol):
    def cutout(self, request: CutoutRequest) -> ImageReference: ...
    def blink(self, images: list[ImageReference]) -> ImageReference: ...
    def difference(self, before: ImageReference, after: ImageReference) -> ImageReference: ...
    def stack(self, images: list[ImageReference]) -> ImageReference: ...
    def timelapse(self, images: list[ImageReference]) -> ImageReference: ...
