from typing import Protocol
from services.observation.domain.models import Observation, SkySearch, TemporalObservation, TemporalSearch


class ObservationCatalog(Protocol):
    def search(self, query: SkySearch) -> list[Observation]: ...


class TemporalObservationCatalog(Protocol):
    def search(self, query: TemporalSearch) -> list[TemporalObservation]: ...


class ObservationRepository(Protocol):
    def upsert(self, observations: list[Observation]) -> int: ...


class ObservationSearchCachePort(Protocol):
    def get(self, query: SkySearch) -> list[Observation] | None: ...
    def put(self, query: SkySearch, observations: list[Observation]) -> None: ...
    def invalidate_all(self) -> None: ...


class TemporalSearchCachePort(Protocol):
    def get(self, query: TemporalSearch) -> list[TemporalObservation] | None: ...
    def put(self, query: TemporalSearch, observations: list[TemporalObservation]) -> None: ...


class TemporalObservationRepository(Protocol):
    def upsert(self, observations: list[TemporalObservation]) -> None: ...
    def get(self, product_id: str) -> TemporalObservation | None: ...
